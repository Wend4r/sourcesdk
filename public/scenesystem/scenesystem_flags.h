#ifndef SCENESYSTEM_FLAGS_H
#define SCENESYSTEM_FLAGS_H
#ifdef _WIN32
#pragma once
#endif

#include <tier0/platform.h>

//-----------------------------------------------------------------------------
// Renderable flags of a scene object. Scene layers render the objects whose
// flags contain all of their required flags and none of their excluded ones.
//-----------------------------------------------------------------------------
enum ESceneObjectFlags : uint64
{
	SCENEOBJECTFLAG_NONE = 0x0,

	SCENEOBJECTFLAG_IS_OPAQUE = 0x0000000000000001ull,
	SCENEOBJECTFLAG_IS_TRANSLUCENT = 0x0000000000000002ull,
	SCENEOBJECTFLAG_ALPHA_TESTED = 0x0000000000000004ull,
	SCENEOBJECTFLAG_HAS_OVERLAY = 0x0000000000000008ull,

	// Set by ISceneSystem::SetObjectBoundsInfinite, cleared by ISceneSystem::SetSceneObjectBounds.
	SCENEOBJECTFLAG_INFINITE_BOUNDS = 0x0000000000000020ull,

	SCENEOBJECTFLAG_VIEWMODEL_LAYER = 0x0000000000000100ull,
	SCENEOBJECTFLAG_GAME_OVERLAY_LAYER = 0x0000000000000400ull,
	SCENEOBJECTFLAG_TOOLSCENE_OVERLAY_LAYER = 0x0000000000010000ull,
	SCENEOBJECTFLAG_TOOLS_UNLIT_LAYER = 0x0000000000020000ull,
	SCENEOBJECTFLAG_HAMMER_PREFAB_STENCIL_LAYER = 0x0000000000080000ull,
	SCENEOBJECTFLAG_HAMMER_SELECTION_STENCIL_LAYER = 0x0000000000100000ull,
	SCENEOBJECTFLAG_HAMMER_ENABLED_STENCIL_LAYER = 0x0000000000200000ull,

	// The world renderer sets it for world objects with OBJECT_TYPE_RENDER_TO_CUBEMAPS.
	SCENEOBJECTFLAG_RENDER_TO_CUBEMAPS = 0x0000000000400000ull,

	SCENEOBJECTFLAG_HAS_AO_PROXIES = 0x0000000010000000ull,
	SCENEOBJECTFLAG_ALPHA_TEST_ZPREPASS = 0x0000000020000000ull,
	SCENEOBJECTFLAG_OCCLUSION_RECULLED = 0x0000000040000000ull,
	SCENEOBJECTFLAG_NEEDS_DYNAMIC_REFLECTION_OR_REFRACTION = 0x0000000080000000ull,
	SCENEOBJECTFLAG_REFLECTS = 0x0000000100000000ull,
	SCENEOBJECTFLAG_DOES_NOT_ACCEPT_DECALS = 0x0000000200000000ull,
	SCENEOBJECTFLAG_WANTS_FRAMEBUFFER_COPY_TEXTURE = 0x0000000400000000ull,
	SCENEOBJECTFLAG_ISSUES_QUERIES = 0x0000000800000000ull,
	SCENEOBJECTFLAG_STATIC_OBJECT = 0x0000001000000000ull,

	// The world renderer sets it for world objects with OBJECT_TYPE_NEEDS_DYNAMIC_SHADOWS.
	SCENEOBJECTFLAG_NEEDS_DYNAMIC_SHADOWS = 0x0000002000000000ull,

	SCENEOBJECTFLAG_CAST_SHADOWS_ENABLED = 0x0000004000000000ull,

	// The object casts shadows only with both MATERIAL_SUPPORTS_SHADOWS and CAST_SHADOWS_ENABLED.
	SCENEOBJECTFLAG_MATERIAL_SUPPORTS_SHADOWS = 0x0000008000000000ull,

	SCENEOBJECTFLAG_NEEDS_STATIC_ENVMAP_BINDING = 0x0000010000000000ull,
	SCENEOBJECTFLAG_WANTS_PROBE_LIGHTING = 0x0000020000000000ull,
	SCENEOBJECTFLAG_NO_Z_PREPASS = 0x0000040000000000ull,
	SCENEOBJECTFLAG_FORWARD_LAYER_ONLY = 0x0000080000000000ull,
	SCENEOBJECTFLAG_NO_MOTION_VECTORS = 0x0000100000000000ull,
	SCENEOBJECTFLAG_CAN_RENDER_INTO_SST = 0x0000200000000000ull,

	SCENEOBJECTFLAG_PIPELINE_SPECIFIC_0 = 0x0001000000000000ull,
	SCENEOBJECTFLAG_PIPELINE_SPECIFIC_1 = 0x0002000000000000ull,
	SCENEOBJECTFLAG_PIPELINE_SPECIFIC_2 = 0x0004000000000000ull,
	SCENEOBJECTFLAG_PIPELINE_SPECIFIC_3 = 0x0008000000000000ull,
	SCENEOBJECTFLAG_PIPELINE_SPECIFIC_4 = 0x0010000000000000ull,
	SCENEOBJECTFLAG_PIPELINE_SPECIFIC_5 = 0x0020000000000000ull,
	SCENEOBJECTFLAG_PIPELINE_SPECIFIC_6 = 0x0040000000000000ull,

	// Set while the object is in the dirty list; the dirty update clears it.
	SCENEOBJECTFLAG_NEEDS_DIRTY_UPDATE = 0x0800000000000000ull,
	SCENEOBJECTFLAG_IS_DISABLED = 0x1000000000000000ull,
	SCENEOBJECTFLAG_IS_LOADED = 0x2000000000000000ull,
	SCENEOBJECTFLAG_DELETED = 0x4000000000000000ull,
	SCENEOBJECTFLAG_DEBUG_BREAK = 0x8000000000000000ull,
};

//-----------------------------------------------------------------------------
// Type flags given to a scene object at creation.
//-----------------------------------------------------------------------------
enum ESceneObjectTypeFlags : uint64
{
	SCENEOBJECTTYPEFLAG_NONE = 0x0,
	SCENEOBJECTTYPEFLAG_HAS_MESH_INSTANCE_DATA = 0x2,
	SCENEOBJECTTYPEFLAG_DELETE_MESH_INSTANCE_DATA = 0x4,
};

#endif // SCENESYSTEM_FLAGS_H
